package com.fireflytv.ui.theme

import androidx.compose.ui.unit.dp

/**
 * TV 端的块面尺寸基线。
 *
 * 只管"行高与留白"，**不管字号** —— 字号已经在 Theme.kt 的 AppTypography 里按
 * 10-foot 调过了（正文 18sp / 次要 16sp）。这里再定义一套字号会和它打架，
 * 将来改一处漏一处。
 *
 * 为什么要单独拉出来：原来散落在各处的 12.dp / 16.dp 是手机密度
 * （一屏塞 6 张小卡还嫌松），电视上 3 米外分不清行与行的边界，
 * 需要更大的块面才看得出层级。
 *
 * 注意这跟 [TvSafeArea] 是两件事，别混：
 * - TvSafeArea 管"别被老电视 overscan 切掉"（48 / 27dp）
 * - TvDimens 管"看着舒不舒服"（行高 / 留白）
 * 两者是叠加关系，不是替代关系。
 */
object TvDimens {
    /** 单行设置项高度。72dp ≈ 一屏 6~7 行，是"看得清"与"一屏能看完"的折中。 */
    val RowHeight = 72.dp

    /** 带说明文字的行高。18sp 标题 + 16sp 说明两行，比单行要高一些才不挤。 */
    val RowHeightTall = 92.dp

    /** 行内水平留白。反白块的文字不贴边，否则整块反白会显得字被挤在角落。 */
    val RowPaddingH = 28.dp

    /**
     * 行间距。第一版按"行高已经够大、间距要收"的思路给了 8dp，
     * 在 1080p 模拟器上实测偏挤 —— 两块反白之间的黑缝只剩十几个像素，
     * 看着像一张卡被切成两半。改回 12dp。
     */
    val RowGap = 12.dp

    /** 分段控件的段高。低于 44dp 在 3 米外会显得单薄，高于 48dp 又会撑破行高。 */
    val SegmentHeight = 44.dp

    /**
     * 分段控件的单段宽度。第一版 124dp 在 1080p 上把 4 个字号档位拉得太散，
     * 每段之间像断开的独立按钮；104dp 更紧凑，仍然容得下「原生播放器」五个字。
     */
    val SegmentWidth = 104.dp

    /**
     * 行反白块的圆角。
     *
     * 8dp 在 1080p / density 320 上约 16 物理像素，相对 72dp 的块高只有 11%，
     * 属于"看得出是圆角、但不会让人注意圆角"的量级。
     *
     * **不要往上加。** 手机端的 16~24dp 圆角放到 10-foot 尺度上会变成
     * 四角发软的胶囊，整页看起来像把移动端卡片直接放大 —— 这正是
     * firefly-tv 原来那套 12/16dp 圆角在电视上显得"怪"的原因之一。
     * 电视 UI 的圆角作用是"让边界不那么生硬"，不是"塑造形体"。
     */
    val RowRadius = 8.dp

    /**
     * 分段条的圆角，比行块略小。它嵌在行块内部，圆角若与行块相同，
     * 在 44dp 高的条上会显得过于圆润，和内层的矩形文字不协调。
     */
    val SegmentRadius = 6.dp
}
